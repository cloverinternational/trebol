// ─── C · evidence ───────────────────────────────────────────────────────────
text(30, 862, "3 · Each claim above is falsifiable from the repository", { size: 15, bold: true, fill: C.ink, max: 800 });
const claims = [
  ["nothing is written into the worktree", "observed run · git status --porcelain empty · checkout holds README.md only"],
  ["root precedence and per-workspace key", ".pi/lib/state/workspace-state.ts:18-40"],
  ["adoption is one-way, never a merge", ".pi/lib/state/workspace-state.ts:42-70 · .pi/test/claw/state-dir.test.ts"],
  ["two orchestrators keep separate cursors", "tools/e2e/claw-two-orchestrators.mjs · PASS across two OS processes"],
  ["no regressions", "claw suite 338/338 · full suite 2299 pass; 3 failures reproduce at HEAD"],
];
y = 892;
for (const [claim, proof] of claims) {
  text(30, y, claim, { size: 12, fill: C.ink, max: 350 });
  text(392, y, proof, { mono: true, size: 11.5, fill: C.muted, max: 780 });
  line(30, y + 8, 1172, y + 8, C.rule, { sw: 1, dash: "2 4" });
  y += 26;
}
text(30, 1050, "Generated, not drawn: the same script asserts widths, paint order and contrast, and the test suite compares this file byte-for-byte.", { size: 11, fill: C.muted, max: 1140 });

// ─── paint-order audit: a rect drawn after text must not cover it ───────────
for (const t of texts) {
  for (const r of rects) {
    if (r.at <= t.at) continue;
    if (t.bx < r.x + r.w && t.bx + t.bw > r.x && t.by < r.y + r.h && t.by + t.bh > r.y) {
      issues.push(`OCCLUDED at (${t.bx.toFixed(0)},${t.by.toFixed(0)}) under rect@${r.at}: "${t.s.slice(0, 46)}"`);
    }
  }
}

// ─── emit ───────────────────────────────────────────────────────────────────
const defs = ["<defs>"];
for (const c of [C.blue, C.teal, C.amber, C.red, C.muted]) {
  defs.push(`<marker id="ah-${c.slice(1)}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="${c}"/></marker>`);
}
defs.push("</defs>");

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="title desc">
<title id="title">Where Trebol's runtime state lives after commit 05e71fe</title>
<desc id="desc">Two views. Ownership: user-authored .swarm inputs stay tracked in the repository, while Claw, the scheduler and opt-in diagnostics now live in a per-user state root keyed by workspace. Behaviour: on first start, an existing state folder means nothing is done or a legacy copy is kept as a conflict; otherwise a legacy in-repo directory is adopted once by rename or staged copy, or a fresh folder is created.</desc>
${defs.join("\n")}
${out.join("\n")}
</svg>
`;

const target = process.argv[2];
if (!target) { console.error("usage: runtime-state-diagram.mjs <out.svg>"); process.exit(2); }
writeFileSync(target, svg);
if (issues.length) {
  console.error(`${issues.length} issue(s):\n` + issues.map((i) => "  " + i).join("\n"));
  process.exit(1);
}
console.log(`wrote ${target} — ${svg.length} bytes, ${texts.length} text nodes, 0 findings`);
