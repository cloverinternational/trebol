#!/usr/bin/env node
/**
 * Generates docs/architecture/runtime-state-relocation.svg.
 *
 * The picture is derived from the committed change (05e71fe) and from an observed
 * run of the real store, not from prose: `tests/runtime-state-diagram.test.ts`
 * regenerates this file and compares it byte-for-byte, and asserts the paths and
 * env names drawn here match `stateRoot`/`workspaceKey`/`clawStateDir` at runtime.
 *
 * The checks below are why the asset is generated instead of hand-drawn. Each one
 * has already caught a real defect in this figure:
 *   - WIDTH      a label wider than its box (silent clipping in every viewer)
 *   - OCCLUDED   a rect painted after text that covers it (invisible, still valid SVG)
 *   - CONTRAST   text that fails WCAG AA against the surface behind it
 * Exit code 1 on any finding, so the figure cannot ship broken.
 */
import { writeFileSync } from "node:fs";

const W = 1200, H = 1080;
const out = [], texts = [], rects = [], issues = [];
let order = 0;

const C = {
  ink: "#1d2b44", body: "#333333", muted: "#5b6472",
  panel: "#f8fafc", rule: "#d7dee8", white: "#ffffff",
  blue: "#3b5b8c", teal: "#1f6f36", amber: "#8a5a00", red: "#a11a14", violet: "#5b3a8e",
  ghost: "#fdf6f6", tint: "#eef4f8",
};

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const est = (s, size, mono) => s.length * size * (mono ? 0.602 : 0.56);

function lum(hex) {
  const n = parseInt(hex.slice(1), 16);
  const ch = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
}
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

function text(x, y, s, o = {}) {
  const size = o.size ?? 12.5, mono = !!o.mono, fill = o.fill ?? C.body, bg = o.bg ?? C.white;
  const w = est(s, size, mono);
  if (o.max != null && w > o.max) issues.push(`WIDTH    ${(w - o.max).toFixed(0)}px over: "${s.slice(0, 52)}"`);
  const need = size >= 18 || (o.bold && size >= 14) ? 3 : 4.5;
  const cr = ratio(fill, bg);
  if (cr < need) issues.push(`CONTRAST ${cr.toFixed(2)}:1 < ${need}:1 — "${s.slice(0, 40)}"`);
  const bx = o.anchor === "middle" ? x - w / 2 : o.anchor === "end" ? x - w : x;
  texts.push({ bx, by: y - size * 0.78, bw: w, bh: size * 1.02, at: order++, s });
  const extra = (o.bold ? ' font-weight="bold"' : "") + (o.anchor ? ` text-anchor="${o.anchor}"` : "");
  out.push(`<text xml:space="preserve" x="${x}" y="${y}" font-size="${size}" fill="${fill}"${extra}>${esc(s)}</text>`);
}

function rect(x, y, w, h, fill, stroke = null, o = {}) {
  const rx = o.rx ?? 10, sw = o.sw ?? 1.5, dash = o.dash ? ` stroke-dasharray="${o.dash}"` : "";
  const st = stroke ? ` stroke="${stroke}" stroke-width="${sw}"` : "";
  rects.push({ x, y, w, h, at: order++ });
  out.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}" fill="${fill}"${st}${dash}/>`);
}

function line(x1, y1, x2, y2, color, o = {}) {
  const dash = o.dash ? ` stroke-dasharray="${o.dash}"` : "";
  const mark = o.arrow ? ` marker-end="url(#ah-${color.slice(1)})"` : "";
  out.push(`<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${color}" stroke-width="${o.sw ?? 1.8}"${dash}${mark}/>`);
}

const row = (x, y, mono_, note, o = {}) => {
  text(x, y, mono_, { mono: true, size: o.size ?? 12.5, fill: o.fill ?? C.ink, max: o.max, bg: o.bg });
  text(o.noteX ?? x + 300, y, note, { size: o.noteSize ?? 12, fill: o.muted, max: o.noteMax, bg: o.bg });
};

// ─── header ──────────────────────────────────────────────────────────────────
out.push(`<rect width="${W}" height="${H}" fill="${C.white}"/>`);
