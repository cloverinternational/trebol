const inputs = [["`.swarm/AGENTS.md`", "instruction context"], ["`.swarm/SWARM.md`", "project rules"],
                ["`.swarm/skills/`", "project skills"], ["`.claude/settings.json`", "hook config"]];
let y = 204;
for (const [a, b] of inputs) { row(48, y, a.replace(/`/g, ""), b, { noteX: 250, bg: C.panel, max: 190, noteMax: 260 }); y += 28; }

rect(48, 316, 480, 104, C.ghost, C.red, { dash: "5 4", rx: 8, sw: 1.2 });
text(62, 338, "written here in 0.9.0, untracked in git status", { size: 11.5, bold: true, fill: C.red, bg: C.ghost, max: 450 });
const ghosts = [".swarmpi/execution/*.json", ".swarm/claw/{control,supervisor,sessions/*}", ".swarm/scheduled_tasks.json"];
let gy = 360;
for (const g of ghosts) { text(62, gy, g, { mono: true, size: 11.5, fill: C.red, bg: C.ghost, max: 450 }); gy += 20; }

text(48, 450, "No blanket .swarm/ ignore: these are inputs, not state.", { size: 11.5, bold: true, fill: C.blue, bg: C.panel, max: 470 });

// right: the state root
rect(660, 122, 512, 348, C.panel, C.teal);
text(680, 152, "Per-user state root", { size: 16, bold: true, fill: C.teal, bg: C.panel, max: 450 });
text(680, 172, "outside the checkout — one folder per workspace", { size: 11.5, fill: C.muted, bg: C.panel, max: 460 });
text(680, 206, "$PI_SWARM_STATE_DIR", { mono: true, size: 12, fill: C.teal, bg: C.panel, max: 440 });
text(680, 221, "else", { size: 10.5, fill: C.muted, bg: C.panel, max: 60 });
text(680, 238, "$XDG_STATE_HOME/pi-swarm", { mono: true, size: 12, fill: C.ink, bg: C.panel, max: 440 });
text(680, 253, "else", { size: 10.5, fill: C.muted, bg: C.panel, max: 60 });
