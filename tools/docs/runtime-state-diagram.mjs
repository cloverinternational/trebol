text(680, 302, "workspaces/<basename>-<sha256(path)[0:12]>/", { mono: true, size: 12, bold: true, fill: C.ink, bg: C.panel, max: 470 });
const tree = [["claw/runs/", "runs, events, goal specs, worker logs"],
              ["claw/sessions/<uuid>.json", "inbox cursor per orchestrator"],
              ["claw/control.json", "plus supervisor.json · 0700 dirs"],
              ["scheduled_tasks.json", "/loop and /goal persistence"]];
y = 330;
for (const [a, b] of tree) { row(680, y, a, b, { noteX: 900, bg: C.panel, max: 210, noteMax: 250 }); y += 30; }
text(680, 456, "diagnostics: written only when PI_SWARM_DIAGNOSTICS=1", { size: 11.5, fill: C.violet, bg: C.panel, max: 470 });

// the move
line(556, 366, 648, 366, C.amber, { arrow: true, sw: 2.2 });
text(556, 344, "moved once", { size: 12, bold: true, fill: C.amber, bg: C.white, max: 90 });
text(556, 388, "never merged", { size: 10.5, fill: C.muted, bg: C.white, max: 95 });

// ─── B · behaviour on first start ───────────────────────────────────────────
text(30, 508, "2 · On first start: three outcomes, taken from adoptLegacyDir's return type", { size: 15, bold: true, fill: C.ink, max: 820 });

const node = (x, y2, w, h, label, stroke, bg = C.panel, size = 12) => {
  rect(x, y2, w, h, bg, stroke, { rx: 9 });
  text(x + w / 2, y2 + h / 2 + 4, label, { size, fill: C.ink, bg, anchor: "middle", max: w - 20 });
};

node(28, 596, 210, 62, "forWorkspace(ws)", C.blue);
node(286, 596, 196, 62, "state folder exists?", C.blue);
node(524, 542, 190, 56, "legacy copy there?", C.amber);
node(524, 672, 190, 56, "legacy dir there?", C.amber);
node(770, 542, 400, 52, "conflict — keep the state folder, leave the legacy copy", C.red, "#fdf6f6", 12);
node(770, 606, 400, 52, "none — nothing to adopt, nothing to merge", C.muted, C.panel, 12);
node(770, 672, 400, 52, "adopted — rename, else a staged copy across devices", C.teal, "#f0f8f2", 12);
node(770, 736, 400, 52, "none — fresh state folder, nothing to move", C.muted, C.panel, 12);

line(238, 627, 282, 627, C.blue, { arrow: true });
line(482, 616, 520, 574, C.amber, { arrow: true });
line(482, 638, 520, 694, C.amber, { arrow: true });
