export type CloverVariant = "full" | "medium" | "tiny";

export const VIEWPORT_MATRIX = [
  [120, 40], [90, 30], [72, 24], [60, 20], [52, 16],
  [48, 12], [40, 10], [36, 8], [30, 6], [24, 5],
] as const;

const FULL = [
  "                          ........                ", "                        ............            ",
  "          ........    ................        ", "          ..........  ....................      ",
  "        ............  ....................      ", "      ................  ....................      ",
  "    ....................  ................        ", "    ....................  ........              ",
  "    ........................          ....          ", "      ..............          ................    ",
  "                      ....    ..................  ", "                ............  ..................  ",
  "            ..............    ..................  ", "          ..................  ..............    ",
  "          ..................  ..............    ", "        ........................  ..............    ",
  "        ........................    ............    ", "          ......................      ........      ",
  "            ..................  ....                ", "                  ........      ....              ",
  "                    ....        ......            ", "                                  ......          ",
  "                                  ........        ", "                                      ........    ",
];
const MEDIUM = ["       ....  ....", "     ..............", "   ..................", "   ..................", "     ..............", "       ........     ", "         ....       ", "         ....       ", "       ......       "];
const TINY = [" . . ", ".....", " . . ", "  .  ", "  .  "];

export function chooseCloverVariant(width: number, height: number): CloverVariant {
  if (width >= 72 && height >= 28) return "full";
  if (width >= 48 && height >= 12) return "medium";
  return "tiny";
}

export function cloverRows(width: number, height: number): string[] {
  const variant = chooseCloverVariant(width, height);
  const source = variant === "full" ? FULL : variant === "medium" ? MEDIUM : TINY;
  return source.slice(0, Math.max(1, height)).map((row) => row.slice(0, Math.max(0, width)));
}
